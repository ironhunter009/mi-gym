/* índice: texto -> entrada, y una sola expresión con todas las variantes (más largas primero) */
const index = new Map();
for(const [keys, kind, es, g] of DICT) for(const k of keys) if(!index.has(k)) index.set(k, {kind, es, g});
const keys = [...index.keys()].sort((a,b)=>b.length-a.length).map(k=>k.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'));
const RE = new RegExp(`(?<![\\w-])(?:${keys.join('|')})(?![\\w-])`, 'g');

const cap = s => s.charAt(0).toUpperCase() + s.slice(1);
function toSpanish(name){
  let s = name.toLowerCase()
    .replace(/\((male|female)\)/g, ' ')
    .replace(/\((back|side) pov\)/g, ' ')
    .replace(/\s+/g, ' ').trim();
  let ver = '';
  s = s.replace(/\bv\.?\s?(\d)\b/, (_, n)=>{ ver = ` (v${n})`; return ' '; });
  const items = [];
  const masked = s.replace(RE, (m, pos)=>{ items.push({pos, ...index.get(m)}); return ' '.repeat(m.length); });
  for(const m of masked.matchAll(/[^\s()]+/g)) items.push({pos:m.index, kind:'raw', es:m[0]});
  items.sort((a,b)=>a.pos-b.pos);

  const cores = items.filter(i=>i.kind===C), raw = items.filter(i=>i.kind==='raw').map(i=>i.es);
  const g = cores.length ? GI[cores[0].g] : 0;
  const mods = [...new Set(items.filter(i=>i.kind===M).map(i=>i.es[g]))];
  const head = cores.map(c=>c.es).join(' y ');
  /* sin repetir lo que el movimiento ya dice ("jalón de tríceps de tríceps", "prensa … en prensa") */
  const objs = [...new Set(items.filter(i=>i.kind===O).map(i=>i.es))].filter(o=>!head.includes(o));
  const equip = [...new Set(items.filter(i=>i.kind===E).map(i=>i.es))].filter(q=>!head.includes(q.split(' ').pop()));
  const known = items.filter(i=>i.kind!=='raw' && i.kind!==X).length;

  /* sin movimiento conocido: la zona pasa a ser el nombre ("Hug knees to chest" -> "Abrazo de rodillas…") */
  const parts = [head,
    objs.length ? (head ? 'de ' : '') + objs.join(' y ') : '',
    raw.join(' '), mods.join(' '), equip.join(' ')].filter(Boolean);
  const es = cap(parts.join(' ').replace(/\s+/g,' ').trim()) + ver;
  return {es, full: raw.length===0 && known>0};
}

